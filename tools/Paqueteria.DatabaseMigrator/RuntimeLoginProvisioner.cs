using System.Text.RegularExpressions;
using Npgsql;

/// <summary>
/// ENV-001: creates or re-keys the three least-privilege runtime LOGIN roles of the pilot database. Each login is
/// <c>LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS</c> and a member of exactly one
/// canonical runtime role (<c>paqueteria_app</c> for the API, <c>paqueteria_worker</c> for the Worker and, since
/// RTM-API-REALTIME-DISPATCHER-ROLE-2026-10-12, <c>paqueteria_realtime</c> for the API's in-process realtime outbox
/// dispatchers).
/// </summary>
/// <remarks>
/// Only SCRAM-SHA-256 verifiers are accepted, never a plaintext password: the deployment workflow derives the
/// verifier from the password it stores in Key Vault, so no plaintext runtime password reaches this process,
/// PostgreSQL statement text or server logs. The canonical roles must already exist (Applied baseline).
/// <para>
/// MDM-001 route S2 (S6 "Nadie la ve ni la teclea"): an optional fourth login, <see cref="MasterDataLogin"/>, for the
/// master-data load job. It exists only while <see cref="MasterDataVerifierVariable"/> is present: then it is created or
/// re-keyed with the same attributes as the runtime logins and is a member of <c>paqueteria_master_data_loader</c>
/// only, so it passes the loader's own operator check (no superuser, BYPASSRLS, runtime or migrator role); when the
/// input is absent it is dropped. Its password is generated by the deployment workflow and kept in Key Vault like the
/// others; only its verifier reaches PostgreSQL.
/// </para>
/// </remarks>
internal static partial class RuntimeLoginProvisioner
{
    internal const string ApiVerifierVariable = "PAQUETERIA_API_LOGIN_VERIFIER";
    internal const string WorkerVerifierVariable = "PAQUETERIA_WORKER_LOGIN_VERIFIER";
    internal const string RealtimeVerifierVariable = "PAQUETERIA_REALTIME_LOGIN_VERIFIER";
    internal const string ApiLogin = "pv_pilot_api";
    internal const string WorkerLogin = "pv_pilot_worker";
    internal const string RealtimeLogin = "pv_pilot_realtime";
    internal const string MasterDataVerifierVariable = "PAQUETERIA_MASTER_DATA_LOGIN_VERIFIER";
    internal const string MasterDataLogin = "pv_pilot_master_data";
    internal const string MasterDataLoaderRole = "paqueteria_master_data_loader";

    /// <summary>What <see cref="RunAsync"/> reports for the master-data login when its verifier is absent.</summary>
    internal const string MasterDataLoginAbsent = "absent";

    internal static readonly (string Login, string RuntimeRole, string VerifierVariable)[] Logins =
    [
        (ApiLogin, "paqueteria_app", ApiVerifierVariable),
        (WorkerLogin, "paqueteria_worker", WorkerVerifierVariable),
        // RTM-API-REALTIME-DISPATCHER-ROLE-2026-10-12: the API's realtime dispatchers never use the Worker login.
        (RealtimeLogin, "paqueteria_realtime", RealtimeVerifierVariable),
    ];

    internal static bool IsScramVerifier(string? value) => value is not null && ScramVerifier().IsMatch(value);

    /// <param name="readSetting">
    /// Resolves a setting by name. The migrator passes the same lookup it uses for its connection, so with
    /// the ADP-001 Key Vault secrets source on (PILOT-KEYVAULT-PRIVATE-APP-READ) the verifiers come from the
    /// mapped Key Vault secrets rather than from environment variables.
    /// </param>
    /// <returns>The master-data login name when it was provisioned, <see cref="MasterDataLoginAbsent"/> when not.</returns>
    internal static async Task<string> RunAsync(string connectionString, Func<string, string?> readSetting,
        CancellationToken cancellationToken)
    {
        var verifiers = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var (login, _, variable) in Logins)
        {
            var verifier = readSetting(variable);
            if (!IsScramVerifier(verifier))
            {
                throw new RuntimeLoginException($"{variable} must be a SCRAM-SHA-256 verifier (4096 iterations).");
            }

            verifiers[login] = verifier!;
        }

        // Optional: absent (unset or empty) drops the login; present must be a verifier like the others.
        var masterDataVerifier = readSetting(MasterDataVerifierVariable);
        if (string.IsNullOrEmpty(masterDataVerifier))
        {
            masterDataVerifier = null;
        }
        else if (!IsScramVerifier(masterDataVerifier))
        {
            throw new RuntimeLoginException(
                $"{MasterDataVerifierVariable} must be a SCRAM-SHA-256 verifier (4096 iterations) or absent.");
        }

        var stage = "connect";
        try
        {
            await using var connection = new NpgsqlConnection(connectionString);
            await connection.OpenAsync(cancellationToken).ConfigureAwait(false);
            await using var transaction = await connection.BeginTransactionAsync(cancellationToken).ConfigureAwait(false);
            foreach (var (login, runtimeRole, _) in Logins)
            {
                stage = $"role-exists:{runtimeRole}";
                if (!await RoleExistsAsync(connection, transaction, runtimeRole, cancellationToken).ConfigureAwait(false))
                {
                    throw new RuntimeLoginException($"canonical role {runtimeRole} is missing; apply the baseline first.");
                }

                stage = $"upsert:{login}";
                await UpsertLoginAsync(connection, transaction, login, runtimeRole, verifiers[login], cancellationToken)
                    .ConfigureAwait(false);

                stage = $"assert:{login}";
                await AssertLoginAsync(connection, transaction, login, runtimeRole, cancellationToken).ConfigureAwait(false);
            }

            string masterDataLogin;
            if (masterDataVerifier is null)
            {
                // No input, no login: a login left from an earlier run is dropped with its membership.
                stage = $"drop:{MasterDataLogin}";
                if (await RoleExistsAsync(connection, transaction, MasterDataLogin, cancellationToken).ConfigureAwait(false))
                {
                    await ExecuteAsync(connection, transaction, $"DROP ROLE {MasterDataLogin}", cancellationToken)
                        .ConfigureAwait(false);
                }

                masterDataLogin = MasterDataLoginAbsent;
            }
            else
            {
                stage = $"role-exists:{MasterDataLoaderRole}";
                if (!await RoleExistsAsync(connection, transaction, MasterDataLoaderRole, cancellationToken).ConfigureAwait(false))
                {
                    throw new RuntimeLoginException(
                        $"canonical role {MasterDataLoaderRole} is missing; apply the baseline and the Pricing lane first.");
                }

                stage = $"upsert:{MasterDataLogin}";
                await UpsertLoginAsync(connection, transaction, MasterDataLogin, MasterDataLoaderRole, masterDataVerifier,
                    cancellationToken).ConfigureAwait(false);

                stage = $"assert:{MasterDataLogin}";
                await AssertLoginAsync(connection, transaction, MasterDataLogin, MasterDataLoaderRole, cancellationToken)
                    .ConfigureAwait(false);
                await AssertMasterDataOperatorAsync(connection, transaction, cancellationToken).ConfigureAwait(false);
                masterDataLogin = MasterDataLogin;
            }

            stage = "commit";
            await transaction.CommitAsync(cancellationToken).ConfigureAwait(false);
            return masterDataLogin;
        }
        catch (PostgresException exception)
        {
            // Only the SQLSTATE is reported: statement text could carry the verifier.
            throw new RuntimeLoginException($"runtime login provisioning failed at {stage} (SQLSTATE {exception.SqlState}).");
        }
    }

    /// <summary>
    /// Creates or re-keys <paramref name="login"/> with the least-privilege attributes and leaves it a member of
    /// <paramref name="role"/> only.
    /// </summary>
    private static async Task UpsertLoginAsync(NpgsqlConnection connection, NpgsqlTransaction transaction,
        string login, string role, string verifier, CancellationToken cancellationToken)
    {
        var verb = await RoleExistsAsync(connection, transaction, login, cancellationToken).ConfigureAwait(false)
            ? "ALTER ROLE {0} WITH"
            : "CREATE ROLE {0}";
        // The login name is a compile-time constant and the verifier matched the strict SCRAM pattern
        // (base64 alphabet, '$' and ':' only), so neither can close the literal.
        await ExecuteAsync(connection, transaction,
            string.Format(System.Globalization.CultureInfo.InvariantCulture, verb, login) +
            " LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD '" +
            verifier + "'",
            cancellationToken).ConfigureAwait(false);

        await using (var others = new NpgsqlCommand("""
            SELECT r.rolname FROM pg_catalog.pg_auth_members m
            JOIN pg_catalog.pg_roles r ON r.oid = m.roleid
            JOIN pg_catalog.pg_roles u ON u.oid = m.member
            WHERE u.rolname = @login AND r.rolname <> @runtime
            """, connection, transaction))
        {
            others.Parameters.AddWithValue("login", login);
            others.Parameters.AddWithValue("runtime", role);
            var stale = new List<string>();
            await using (var reader = await others.ExecuteReaderAsync(cancellationToken).ConfigureAwait(false))
            {
                while (await reader.ReadAsync(cancellationToken).ConfigureAwait(false))
                {
                    stale.Add(reader.GetString(0));
                }
            }

            foreach (var membership in stale)
            {
                await ExecuteAsync(connection, transaction,
                    $"REVOKE {QuoteIdentifier(membership)} FROM {login}", cancellationToken).ConfigureAwait(false);
            }
        }

        await ExecuteAsync(connection, transaction, $"GRANT {role} TO {login}", cancellationToken)
            .ConfigureAwait(false);
    }

    /// <summary>
    /// The master-data login passes the loader's own operator check (<c>MasterDataLoader</c>): it can SET ROLE to the
    /// loader and reaches no runtime or migrator role, directly or through the loader.
    /// </summary>
    private static async Task AssertMasterDataOperatorAsync(NpgsqlConnection connection, NpgsqlTransaction transaction,
        CancellationToken cancellationToken)
    {
        await using var command = new NpgsqlCommand($"""
            SELECT pg_catalog.pg_has_role('{MasterDataLogin}', '{MasterDataLoaderRole}', 'SET')
               AND NOT pg_catalog.pg_has_role('{MasterDataLogin}', '{MasterDataLoaderRole}', 'USAGE')
               AND NOT pg_catalog.pg_has_role('{MasterDataLogin}', 'paqueteria_app', 'MEMBER')
               AND NOT pg_catalog.pg_has_role('{MasterDataLogin}', 'paqueteria_worker', 'MEMBER')
               AND NOT pg_catalog.pg_has_role('{MasterDataLogin}', 'paqueteria_realtime', 'MEMBER')
               AND NOT pg_catalog.pg_has_role('{MasterDataLogin}', 'paqueteria_migrator', 'MEMBER')
            """, connection, transaction);
        if (await command.ExecuteScalarAsync(cancellationToken).ConfigureAwait(false) is not true)
        {
            throw new RuntimeLoginException($"{MasterDataLogin} does not pass the master-data loader's operator check.");
        }
    }

    private static async Task AssertLoginAsync(NpgsqlConnection connection, NpgsqlTransaction transaction,
        string login, string runtimeRole, CancellationToken cancellationToken)
    {
        await using var command = new NpgsqlCommand("""
            SELECT u.rolcanlogin AND NOT u.rolinherit AND NOT u.rolsuper AND NOT u.rolcreatedb
                   AND NOT u.rolcreaterole AND NOT u.rolreplication AND NOT u.rolbypassrls
                   AND (SELECT array_agg(r.rolname ORDER BY r.rolname) FROM pg_catalog.pg_auth_members m
                        JOIN pg_catalog.pg_roles r ON r.oid = m.roleid WHERE m.member = u.oid) = ARRAY[@runtime]::name[]
            FROM pg_catalog.pg_roles u WHERE u.rolname = @login
            """, connection, transaction);
        command.Parameters.AddWithValue("login", login);
        command.Parameters.AddWithValue("runtime", runtimeRole);
        if (await command.ExecuteScalarAsync(cancellationToken).ConfigureAwait(false) is not true)
        {
            throw new RuntimeLoginException($"{login} does not have the exact least-privilege runtime shape.");
        }
    }

    private static async Task<bool> RoleExistsAsync(NpgsqlConnection connection, NpgsqlTransaction transaction,
        string role, CancellationToken cancellationToken)
    {
        await using var command = new NpgsqlCommand(
            "SELECT EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = @role)", connection, transaction);
        command.Parameters.AddWithValue("role", role);
        return await command.ExecuteScalarAsync(cancellationToken).ConfigureAwait(false) is true;
    }

    private static async Task ExecuteAsync(NpgsqlConnection connection, NpgsqlTransaction transaction,
        string sql, CancellationToken cancellationToken)
    {
        await using var command = new NpgsqlCommand(sql, connection, transaction);
        await command.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);
    }

    private static string QuoteIdentifier(string identifier) => "\"" + identifier.Replace("\"", "\"\"", StringComparison.Ordinal) + "\"";

    // SCRAM-SHA-256$<iterations>:<base64 16-byte salt>$<base64 StoredKey>:<base64 ServerKey>
    [GeneratedRegex(@"^SCRAM-SHA-256\$4096:[A-Za-z0-9+/]{22}==\$[A-Za-z0-9+/]{43}=:[A-Za-z0-9+/]{43}=$",
        RegexOptions.CultureInvariant)]
    private static partial Regex ScramVerifier();
}

internal sealed class RuntimeLoginException(string message) : Exception(message);
